@OptIn(FlowPreview::class)
@Composable
fun rememberStrength(
    app: FactorSeal,
    state: TextFieldState,
): Strength? {
    var strength by remember(state) { mutableStateOf<Strength?>(null) }
    LaunchedEffect(state) {
        snapshotFlow { state.text.toString() }
            .debounce(300)
            .collect { text ->
                strength = if (text.isEmpty()) null else runCatching { app.vault.ask<Response.Rating>(Request.RatePassword(text)).strength }.getOrNull()
            }
    }
    return strength
}

private val Lengths = 8..64
private val WordCounts = 12..24 step 3

@Composable
fun Generator(
    app: FactorSeal,
    onDismiss: () -> Unit,
    onUse: (String) -> Unit,
) {
    var options by remember { mutableStateOf(app.preferences.generator) }
    var generated by remember { mutableStateOf<Response.Generated?>(null) }
    var failed by remember { mutableStateOf(false) }
    var revealed by remember { mutableStateOf(false) }
    var round by remember { mutableIntStateOf(0) }
    LaunchedEffect(options, round) {
        runCatching { app.call<Response.Generated>(Request.Generate(options)) }
            .onSuccess {
                generated = it
                failed = false
            }.onFailure {
                generated = null
                failed = true
            }
    }
    val colors = Theme.colors
    Sheet(stringResource(Res.string.generate_password), onDismiss) {
        Row(horizontalArrangement = Arrangement.spacedBy(4.dp)) {
            Button(
                stringResource(Res.string.random),
                onClick = { options = options.copy(style = GeneratorStyle.Random) },
                selected = options.style == GeneratorStyle.Random,
            )
            Button(
                stringResource(Res.string.words),
                onClick = { options = options.copy(style = GeneratorStyle.Words) },
                selected = options.style == GeneratorStyle.Words,
            )
        }
        Row(horizontalArrangement = Arrangement.spacedBy(8.dp), verticalAlignment = Alignment.Top) {
            Box(
                Modifier
                    .weight(1f)
                    .height(96.dp)
                    .background(colors.muted, Shapes.input)
                    .verticalScroll(rememberScrollState())
                    .padding(horizontal = 12.dp, vertical = 8.dp),
            ) {
                val password = generated?.password
                when {
                    failed -> Text(stringResource(Res.string.could_not_generate), color = colors.danger)
                    password != null -> Text(if (revealed) password else "•".repeat(password.length), style = Type.mono)
                }
            }
            Column(verticalArrangement = Arrangement.spacedBy(4.dp)) {
                IconButton(
                    if (revealed) Res.drawable.icon_eye_off else Res.drawable.icon_eye,
                    stringResource(if (revealed) Res.string.hide_password else Res.string.show_password),
                    onClick = { revealed = !revealed },
                )
                IconButton(Res.drawable.icon_redo, stringResource(Res.string.generate_another), onClick = { round++ })
            }
        }
        generated?.let { StrengthMeter(it.strength, stringResource(it.strength.label())) }
        Column(verticalArrangement = Arrangement.spacedBy(12.dp)) {
            val random = options.style == GeneratorStyle.Random
            val size = if (random) options.length else options.words
            val label = stringResource(if (random) Res.string.length else Res.string.words)
            Row(Modifier.fillMaxWidth()) {
                Text(label, Modifier.weight(1f))
                Text(size.toString(), color = colors.mutedForeground)
            }
            Slider(
                value = size,
                range = if (random) Lengths else WordCounts,
                onChange = { value -> options = if (random) options.copy(length = value) else options.copy(words = value) },
                description = label,
                modifier = Modifier.padding(horizontal = 8.dp),
            )
            if (random) {
                Toggle(stringResource(Res.string.digits), options.digits) { options = options.copy(digits = it) }
                Toggle(stringResource(Res.string.symbols), options.symbols) { options = options.copy(symbols = it) }
            }
        }
        Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.End) {
            Button(
                stringResource(Res.string.use_password),
                onClick = {
                    val password = generated?.password ?: return@Button
                    app.update(app.preferences.copy(generator = options))
                    onUse(password)
                },
                variant = Variant.Primary,
                enabled = generated != null,
            )
        }
    }
}

@Composable
private fun Toggle(
    label: String,
    checked: Boolean,
    onChange: (Boolean) -> Unit,
) {
    Row(Modifier.fillMaxWidth().defaultMinSize(minHeight = 40.dp), verticalAlignment = Alignment.CenterVertically) {
        Text(label, Modifier.weight(1f))
        Switch(checked, onChange, label)
    }
}

@Composable
fun Scanner(
    app: FactorSeal,
    onDismiss: () -> Unit,
    accept: (Scan) -> Boolean,
    rejected: Message = message(Res.string.not_otp_qr_code),
    onResult: (Scan) -> Unit,
) {
    var problem by remember { mutableStateOf<Message?>(null) }
    var unavailable by remember { mutableStateOf(false) }
    var done by remember { mutableStateOf(false) }
    val scope = rememberCoroutineScope()
    fun handle(
        scan: Scan,
        pasted: Boolean,
    ) {
        if (done) return
        when {
            accept(scan) -> {
                done = true
                onResult(scan)
            }

            scan is Scan.Unsupported || scan is Scan.Pairing || scan is Scan.OneTimePassword -> problem = rejected

            pasted -> problem = message(Res.string.no_qr_code)
        }
    }
    Sheet(stringResource(Res.string.scan_qr_code), onDismiss) {
        Box(
            Modifier
                .widthIn(max = 420.dp)
                .fillMaxWidth()
                .aspectRatio(1f)
                .align(Alignment.CenterHorizontally)
                .clip(Shapes.card)
                .background(Color.Black),
            contentAlignment = Alignment.Center,
        ) {
            if (unavailable) {
                Text(
                    stringResource(Res.string.camera_unavailable),
                    Modifier.padding(24.dp),
                    color = Color.White,
                    align = TextAlign.Center,
                )
            } else {
                app.host.Scanner(
                    vault = app.vault,
                    onScan = { handle(it, pasted = false) },
                    onUnavailable = { unavailable = true },
                    modifier = Modifier.fillMaxSize(),
                )
            }
        }
        problem?.let { Caption(it.text(), color = Theme.colors.danger) }
        Button(
            stringResource(Res.string.paste_from_clipboard),
            onClick = {
                val text = app.host.paste().orEmpty()
                scope.launch {
                    val scan = runCatching { app.vault.ask<Response.Scanned>(Request.Classify(text)).scan }.getOrDefault(Scan.Nothing)
                    handle(scan, pasted = true)
                    if (scan is Scan.OneTimePassword && accept(scan)) {
                        app.host.clearClipboard(text)
                        app.toast(message(Res.string.removed_setup_link))
                    }
                }
            },
            modifier = Modifier.fillMaxWidth(),
            icon = Res.drawable.glyph_paste,
        )
    }
}
